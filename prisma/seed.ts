/**
 * Seeds a demo owner, a data room with sample PDFs, two invited guests and some
 * realistic engagement data so the analytics pages have something to show.
 *
 *   npm run seed
 *
 * Owner login: owner@example.com / password123
 */
import { PrismaClient } from "@prisma/client";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { createHash, randomBytes, scryptSync } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";

const prisma = new PrismaClient();

function hashPassword(password: string): string {
  const salt = randomBytes(16).toString("hex");
  return `${salt}:${scryptSync(password, salt, 64).toString("hex")}`;
}
const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
const token = () => randomBytes(24).toString("base64url");

async function samplePdf(title: string, pages: number): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  for (let i = 1; i <= pages; i++) {
    const page = doc.addPage([612, 792]);
    page.drawText(title, { x: 56, y: 720, size: 22, font: bold, color: rgb(0.1, 0.1, 0.2) });
    page.drawText(`Page ${i} of ${pages}`, { x: 56, y: 696, size: 11, font, color: rgb(0.4, 0.4, 0.4) });
    const lines = [
      "This is a sample document generated by the seed script.",
      "Upload your own PDFs from the Documents tab to replace it.",
      "",
      "Lorem ipsum dolor sit amet, consectetur adipiscing elit. Integer nec odio.",
      "Praesent libero. Sed cursus ante dapibus diam. Sed nisi. Nulla quis sem at",
      "nibh elementum imperdiet. Duis sagittis ipsum. Praesent mauris. Fusce nec",
      "tellus sed augue semper porta. Mauris massa. Vestibulum lacinia arcu eget nulla.",
    ];
    lines.forEach((l, idx) => page.drawText(l, { x: 56, y: 640 - idx * 18, size: 11, font }));
    page.drawRectangle({ x: 56, y: 200, width: 500, height: 300, borderColor: rgb(0.8, 0.8, 0.85), borderWidth: 1 });
    page.drawText(`Figure ${i}: placeholder chart`, { x: 70, y: 480, size: 10, font, color: rgb(0.5, 0.5, 0.5) });
  }
  return doc.save();
}

async function storeFile(roomId: string, name: string, bytes: Uint8Array): Promise<string> {
  const root = path.isAbsolute(process.env.STORAGE_DIR || "") ? (process.env.STORAGE_DIR as string) : path.join(process.cwd(), process.env.STORAGE_DIR || "./storage");
  const key = path.posix.join(roomId, `${randomBytes(16).toString("base64url")}.pdf`);
  await fs.mkdir(path.join(root, roomId), { recursive: true });
  await fs.writeFile(path.join(root, key), bytes);
  return key;
}

async function main() {
  const email = "owner@example.com";
  if (await prisma.user.findUnique({ where: { email } })) {
    console.log("Seed data already present (owner@example.com exists). Nothing to do.");
    return;
  }
  const owner = await prisma.user.create({ data: { email, name: "Dana Owner", passwordHash: hashPassword("password123") } });

  const ndaBody = `This Confidentiality and Non-Disclosure Agreement is entered into between Dana Owner (the "Disclosing Party") and the individual accepting this Agreement (the "Recipient") in connection with access to the data room "Project Falcon – Series A".

1. Confidential Information means all documents, data and materials made available through the data room.

2. The Recipient will hold the Confidential Information in strict confidence, use it solely to evaluate a potential investment, and not disclose it to any third party.

3. The Recipient acknowledges that access is logged, including documents opened and time spent, and that documents may be watermarked with the Recipient's identity.

4. These obligations last three (3) years from acceptance.

5. By typing their name and confirming acceptance, the Recipient agrees to be legally bound by this Agreement.`;

  const room = await prisma.dataRoom.create({
    data: {
      ownerId: owner.id,
      name: "Project Falcon – Series A",
      description: "Financials, cap table and legal documents for prospective investors.",
      ndaVersions: { create: { version: 1, title: "Confidentiality and Non-Disclosure Agreement", body: ndaBody, bodyHash: sha256(ndaBody) } },
    },
    include: { ndaVersions: true },
  });
  const nda = room.ndaVersions[0];

  const financials = await prisma.folder.create({ data: { roomId: room.id, name: "Financials", sortOrder: 1 } });
  const legal = await prisma.folder.create({ data: { roomId: room.id, name: "Legal", sortOrder: 2 } });

  const docSpecs = [
    { title: "Investor Deck", pages: 12, folderId: null as string | null, description: "Company overview and the round." },
    { title: "FY2025 Financial Statements", pages: 8, folderId: financials.id, description: "Audited P&L, balance sheet and cash flow." },
    { title: "Three-year Forecast Model", pages: 5, folderId: financials.id, description: "Assumptions on page 3." },
    { title: "Cap Table", pages: 2, folderId: legal.id, description: "Fully diluted, pre-money." },
    { title: "Articles of Incorporation", pages: 15, folderId: legal.id, description: "" },
  ];
  const docs = [];
  for (const [i, spec] of docSpecs.entries()) {
    const bytes = await samplePdf(spec.title, spec.pages);
    const key = await storeFile(room.id, spec.title, bytes);
    const fileName = `${spec.title.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}.pdf`;
    const doc = await prisma.document.create({
      data: {
        roomId: room.id,
        folderId: spec.folderId,
        title: spec.title,
        description: spec.description,
        fileName,
        mimeType: "application/pdf",
        size: bytes.byteLength,
        storageKey: key,
        pageCount: spec.pages,
        sortOrder: i + 1,
        versions: { create: { version: 1, fileName, mimeType: "application/pdf", size: bytes.byteLength, storageKey: key, pageCount: spec.pages } },
      },
    });
    docs.push(doc);
  }

  const guests = [
    { email: "alex@falconcapital.com", name: "Alex Rivera", company: "Falcon Capital", signed: true, engagement: [0.9, 1, 1, 0.6, 0.2] },
    { email: "sam@northwind.vc", name: "Sam Chen", company: "Northwind Ventures", signed: true, engagement: [1, 0.4, 0, 0.8, 0] },
    { email: "jordan@latefund.com", name: "", company: "", signed: false, engagement: [0, 0, 0, 0, 0] },
  ];
  const dayMs = 86400 * 1000;
  for (const g of guests) {
    const guest = await prisma.guest.create({ data: { email: g.email, name: g.name, company: g.company } });
    const invite = await prisma.invite.create({
      data: {
        roomId: room.id,
        guestId: guest.id,
        invitedById: owner.id,
        token: token(),
        status: g.signed ? "active" : "pending",
        expiresAt: new Date(Date.now() + 30 * dayMs),
        acceptedAt: g.signed ? new Date(Date.now() - 3 * dayMs) : null,
        lastSeenAt: g.signed ? new Date(Date.now() - dayMs / 2) : null,
      },
    });
    await prisma.auditEvent.create({ data: { roomId: room.id, actorType: "owner", actorId: owner.id, actorEmail: owner.email, action: "invite.create", targetType: "invite", targetId: invite.id, targetName: g.email, createdAt: new Date(Date.now() - 4 * dayMs) } });
    if (!g.signed) continue;
    await prisma.ndaSignature.create({
      data: { roomId: room.id, ndaVersionId: nda.id, guestId: guest.id, inviteId: invite.id, signerName: g.name, signerEmail: g.email, signerCompany: g.company, ipAddress: "203.0.113.42", userAgent: "Mozilla/5.0 (seed)", signedAt: new Date(Date.now() - 3 * dayMs) },
    });
    await prisma.auditEvent.create({ data: { roomId: room.id, actorType: "guest", actorId: guest.id, actorEmail: g.email, action: "nda.sign", targetType: "nda", targetId: nda.id, targetName: `${nda.title} v1`, ipAddress: "203.0.113.42", createdAt: new Date(Date.now() - 3 * dayMs) } });

    for (const [i, weight] of g.engagement.entries()) {
      if (weight === 0) continue;
      const doc = docs[i];
      const sessions = weight >= 0.8 ? 2 : 1;
      for (let s = 0; s < sessions; s++) {
        const startedAt = new Date(Date.now() - (2 - s) * dayMs - Math.floor(Math.random() * 6) * 3600 * 1000);
        const total = Math.round(weight * (120 + Math.random() * 600));
        // Distribute time across pages, front-loaded with a hot spot.
        const pageCount = doc.pageCount ?? 1;
        const hot = Math.min(pageCount, 1 + Math.floor(Math.random() * pageCount));
        const raw = Array.from({ length: pageCount }, (_, p) => (p + 1 === hot ? 3 : 1) * Math.max(0.1, 1 - p / pageCount));
        const sum = raw.reduce((a, b) => a + b, 0);
        const pageTimes = raw.map((r, p) => ({ page: p + 1, seconds: Math.round((r / sum) * total) })).filter((x) => x.seconds > 0);
        const maxPage = Math.max(...pageTimes.map((p) => p.page));
        const vs = await prisma.viewSession.create({
          data: { roomId: room.id, documentId: doc.id, guestId: guest.id, inviteId: invite.id, startedAt, lastHeartbeatAt: new Date(startedAt.getTime() + total * 1000), endedAt: new Date(startedAt.getTime() + total * 1000), activeSeconds: pageTimes.reduce((a, b) => a + b.seconds, 0), maxPage, ipAddress: "203.0.113.42", pageTimes: { create: pageTimes } },
        });
        await prisma.auditEvent.create({ data: { roomId: room.id, actorType: "guest", actorId: guest.id, actorEmail: g.email, action: "document.view", targetType: "document", targetId: doc.id, targetName: doc.title, metadata: JSON.stringify({ sessionId: vs.id }), ipAddress: "203.0.113.42", createdAt: startedAt } });
      }
    }
    if (g.email.startsWith("alex")) {
      await prisma.question.create({ data: { roomId: room.id, documentId: docs[2].id, guestId: guest.id, body: "What churn assumption drives the 2027 revenue line on page 3?", createdAt: new Date(Date.now() - dayMs) } });
    }
  }

  const invites = await prisma.invite.findMany({ where: { roomId: room.id }, include: { guest: true } });
  console.log("\nSeeded demo data.\n");
  console.log("Owner login:   owner@example.com / password123");
  console.log(`Room:          ${room.name}`);
  console.log("\nGuest invitation links (open in a private window):");
  for (const inv of invites) console.log(`  ${inv.guest.email.padEnd(28)} ${process.env.APP_URL || "http://localhost:3000"}/invite/${inv.token}`);
  console.log("");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
